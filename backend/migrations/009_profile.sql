-- 009_profile.sql
-- Поля профиля жителя, которых не хватало для «дозаполнения».
--
-- Дата рождения нужна для:
--   - корректного обращения (по имени или имени-отчеству);
--   - возрастных ограничений отдельных сервисов (позже);
--   - соответствия требованиям к учёту ПДн (состав данных фиксируется).
--
-- Остальные поля профиля уже есть: users.email, users.phone, users.full_name.
-- ============================================================================

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS birth_date date;

COMMENT ON COLUMN users.birth_date IS
  'Дата рождения. Заполняется жителем добровольно в профиле; используется для обращения и возрастных правил сервисов.';

-- Дата рождения не может быть в будущем и раньше 1900 года
ALTER TABLE users
  ADD CONSTRAINT users_birth_date_sane
  CHECK (birth_date IS NULL OR (birth_date >= '1900-01-01' AND birth_date <= CURRENT_DATE));
