-- ============================================================================
-- 010_snils.sql
-- СНИЛС жителя — для сверки с реестром собственников управляющей компании.
--
-- Зачем: подтверждение привязки к квартире сейчас ручное. Если УК передаст
-- реестр собственников со СНИЛС, привязку можно подтверждать автоматически:
-- человек ввёл СНИЛС в профиле — совпало — привязка подтверждена.
--
-- Почему храним в открытом виде: СНИЛС нужен для сравнения, хеш не позволит
-- показать человеку его же номер и не даст понять, что именно не совпало.
-- Доступ ограничен: владелец видит свой, сотрудники УК — только если это
-- разрешено политикой (см. docs/DECISIONS.md, ЕСИА отложена).
-- ============================================================================

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS snils text;

-- Только 11 цифр без разделителей: формат приводится на сервере,
-- чтобы 123-456-789 01 и 12345678901 не стали разными значениями.
ALTER TABLE users
  ADD CONSTRAINT users_snils_format
  CHECK (snils IS NULL OR snils ~ '^[0-9]{11}$');

COMMENT ON COLUMN users.snils IS
  'СНИЛС, 11 цифр без разделителей. Заполняется жителем добровольно, используется для сверки с реестром собственников УК.';
