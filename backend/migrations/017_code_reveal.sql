-- ============================================================================
-- 017_code_reveal.sql
-- Код доступа можно посмотреть в кабинете владельца.
--
-- Раньше код показывался один раз: в базе лежал только bcrypt-хеш. Владелец
-- справедливо спросил — почему нельзя посмотреть? Код не является паролем
-- пользователя, это «ключ от двери», и владелец вправе его видеть.
--
-- Компромисс: хеш остаётся для проверки, а рядом лежит ШИФРОВАННАЯ копия
-- (AES-256-GCM, ключ выводится из секрета приложения). Украденный дамп базы
-- без ключа приложения кодов не раскрывает.
-- ============================================================================

ALTER TABLE apartment_members
  ADD COLUMN IF NOT EXISTS access_code_sealed text;

COMMENT ON COLUMN apartment_members.access_code_sealed IS
  'Зашифрованная копия кода доступа (AES-256-GCM) — чтобы владелец мог посмотреть код в кабинете. Расшифровывается только сервером.';
