-- ============================================================================
-- 020_intercom_hangup.sql
-- Сброс звонка на панели после ответа жителя.
--
-- Проблема (замечена на стенде): житель нажимает «Открыть», дверь открывается,
-- но панель продолжает вызов — на табло и в динамике разговор не завершён.
-- Причина: мы меняли только свою запись в базе, а Asterisk об этом не знал.
--
-- Чтобы попросить Asterisk положить трубку, нужен канал — его присылает AMI
-- в событии Newchannel (поле Channel), например PJSIP/6001-00000002.
-- ============================================================================

ALTER TABLE intercom_calls
  ADD COLUMN IF NOT EXISTS ami_channel text;

COMMENT ON COLUMN intercom_calls.ami_channel IS
  'Имя канала Asterisk, с которого пришёл звонок. По нему отправляется Hangup, когда житель открыл дверь или отклонил вызов.';
