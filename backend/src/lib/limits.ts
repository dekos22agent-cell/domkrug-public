/**
 * Ограничения частоты запросов.
 *
 * Зачем отдельный помощник: в development лимиты НЕ отключаются, а
 * увеличиваются. Отключить их проще всего, но тогда код лимитера не
 * выполняется в разработке вообще, и первая же ошибка в нём всплывёт
 * в production — на живых пользователях.
 *
 * Увеличение вместо отключения решает обе задачи:
 *   - тесты и ручная проверка на одном IP не упираются в лимит;
 *   - сам механизм продолжает работать и проверяться.
 */
import { config } from '../config.js';

/** Во сколько раз ослаблять лимиты в разработке. */
const DEV_FACTOR = 50;

export function scaledLimit(max: number): number {
  return config.isProduction ? max : max * DEV_FACTOR;
}
