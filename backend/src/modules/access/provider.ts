/**
 * Провайдеры доступа к точкам: двери, калитки, шлагбаумы.
 *
 * Зачем абстракция: вендоры СКУД отличаются всем — транспортом (HTTP, SIP,
 * Modbus), авторизацией, форматом ответа. Если писать интеграцию сразу под
 * конкретного производителя, вторая интеграция потребует переделки экранов
 * и логики прав.
 *
 * Поэтому сначала контракт, потом реализация:
 *   mock      — работает сейчас, ничего не открывает физически;
 *   hikvision — вызывная панель Hikvision по ISAPI (DS-KD9633-E6);
 *   basip     — когда появится железо BAS-IP;
 *   akvox     — если УК выберет Akuvox;
 *   relay     — универсальный вариант для шлагбаумов через реле.
 *
 * Добавление вендора = новый файл с реализацией интерфейса и запись в реестре.
 * Ни модель данных, ни маршруты, ни экраны при этом не меняются.
 */

export type AccessPointKind = 'entrance_door' | 'wicket' | 'barrier' | 'gate' | 'parking';

export interface AccessPointInfo {
  id: string;
  kind: AccessPointKind;
  name: string;
  /** Подсказка жителю: что именно откроется */
  instruction: string | null;
  provider: string;
  /**
   * Адрес точки ВНУТРИ устройства: номер двери/реле у контроллера, номер
   * входа у панели. Из `access_points.provider_ref`.
   *
   * Зачем в контракте: одно устройство обслуживает несколько точек (у панели
   * DS-KD9633 два реле — замок и калитка), и провайдеру нужно знать, какое
   * именно реле дёргать. Хранить это в провайдере нельзя: он один на все
   * точки, а точек у одного устройства несколько.
   */
  ref?: string | null;
}

export interface OpenResult {
  ok: boolean;
  /** Короткое сообщение для интерфейса: «Открыто», «Устройство недоступно» */
  message: string;
  /** Сколько секунд дверь остаётся открытой, если устройство это сообщает */
  holdSeconds?: number;
}

/**
 * Что должен уметь провайдер.
 *
 * `getStream` необязателен: шлагбауму видео не нужно, домофону — нужно.
 * Необязательность здесь честнее, чем заглушка с пустым потоком.
 */
export interface AccessProvider {
  readonly name: string;

  /** Открыть точку. Вызывается только после проверки прав в сервисе. */
  open(point: AccessPointInfo): Promise<OpenResult>;

  /** Откуда брать видео, если оно есть. */
  getStream?(point: AccessPointInfo): Promise<AccessStream | null>;
}

export interface AccessStream {
  /** Тип потока: браузер не умеет RTSP, поэтому либо SIP, либо WebRTC/HLS */
  type: 'sip' | 'webrtc' | 'hls';
  url: string;
}
