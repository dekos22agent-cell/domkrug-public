/**
 * Проверка СНИЛС — модульные тесты.
 *
 * Проверяем не только «правильные номера проходят», но и обратное:
 * опечатка в одной цифре должна отсекаться. Иначе проверка бесполезна.
 */
import { describe, expect, it } from 'vitest';
import { formatSnils, normalizeSnils, validateSnils } from '../../src/lib/snils.js';

describe('СНИЛС', () => {
  describe('нормализация', () => {
    it('убирает дефисы и пробелы', () => {
      expect(normalizeSnils('123-456-789 01')).toBe('12345678901');
      expect(normalizeSnils('123 456 789 01')).toBe('12345678901');
      expect(normalizeSnils('12345678901')).toBe('12345678901');
    });
  });

  describe('форматирование', () => {
    it('показывает в привычном виде', () => {
      expect(formatSnils('12345678901')).toBe('123-456-789 01');
    });

    it('не ломает неполное значение', () => {
      expect(formatSnils('12345')).toBe('12345');
    });
  });

  describe('контрольное число', () => {
    // 112-233-445 95 — пример с корректной контрольной суммой
    it('принимает номер с верной контрольной суммой', () => {
      expect(validateSnils('11223344595')).toBeNull();
      expect(validateSnils('112-233-445 95')).toBeNull();
    });

    it('отклоняет номер с неверной контрольной суммой', () => {
      const error = validateSnils('11223344596');
      expect(error).toContain('контрольной суммы');
    });

    it('отклоняет номер, изменённый в одной цифре', () => {
      // Любая замена в первых девяти цифрах ломает контрольное число
      expect(validateSnils('11223344695')).not.toBeNull();
      expect(validateSnils('11223343595')).not.toBeNull();
    });

    it('отклоняет короткий и длинный номер', () => {
      expect(validateSnils('1122334459')).toContain('11 цифр');
      expect(validateSnils('112233445951')).toContain('11 цифр');
    });

    it('отклоняет зарезервированный диапазон', () => {
      // Номера меньше 001-001-998 не выдавались. Граница — 001-001-998,
      // поэтому проверяем на единицу ниже неё.
      expect(validateSnils('00100199795')).toContain('не выдавался');
    });

    it('отклоняет буквы', () => {
      expect(validateSnils('1122334459a')).toContain('11 цифр');
    });
  });
});
